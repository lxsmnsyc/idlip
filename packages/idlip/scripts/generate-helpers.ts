// Writes `src/core/helpers-source.ts`: the text of each helper of `idlip/helpers`, taken from
// the TypeScript sources at build time. The compiler then never reads a function's text at run
// time, so a minifier or another bundler cannot change the output of a chunk.
// `node scripts/generate-helpers.ts` writes the file. With `--check` it fails when the file is
// out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseSync } from 'oxc-parser';
import { transformWithOxc } from 'vite';
import type { Function as FunctionNode, Statement } from '@oxc-project/types';

const ROOT = path.join(import.meta.dirname, '../src/core');
const OUTPUT = path.join(ROOT, 'helpers-source.ts');
const SOURCES = ['helpers.ts', 'dynamic.ts'];

async function readFunctions(file: string): Promise<{ code: string; nodes: Statement[] }> {
  const input = path.join(ROOT, file);
  const result = await transformWithOxc(readFileSync(input, 'utf8'), input, { lang: 'ts' });
  return { code: result.code, nodes: parseSync(`${file}.js`, result.code).program.body };
}

function getDeclared(node: Statement): FunctionNode | undefined {
  // `export function name` and `function name` both declare a function
  const target = node.type === 'ExportNamedDeclaration' ? node.declaration : node;
  return target?.type === 'FunctionDeclaration' ? target : undefined;
}

/** Lists the keys of the `HELPERS` table, in the order a chunk module holds the helpers. */
function listHelperNames(node: Statement): string[] | undefined {
  if (node.type !== 'VariableDeclaration') {
    return undefined;
  }
  for (const declarator of node.declarations) {
    if (
      declarator.id.type === 'Identifier' &&
      declarator.id.name === 'HELPERS' &&
      declarator.init?.type === 'ObjectExpression'
    ) {
      const names: string[] = [];
      for (const property of declarator.init.properties) {
        if (property.type === 'Property' && property.key.type === 'Identifier') {
          names.push(property.key.name);
        }
      }
      return names;
    }
  }
  return undefined;
}

async function printSource(): Promise<string> {
  const texts = new Map<string, string>();
  let names: string[] = [];
  for (const file of SOURCES) {
    const { code, nodes } = await readFunctions(file);
    for (const node of nodes) {
      const declared = getDeclared(node);
      if (declared?.id) {
        texts.set(declared.id.name, code.slice(declared.start, declared.end));
      }
      if (file === 'helpers.ts') {
        names = listHelperNames(node) ?? names;
      }
    }
  }
  const lines: string[] = [];
  for (const name of names) {
    const text = texts.get(name);
    if (text === undefined) {
      throw new Error(`The helper ${name} has no function declaration`);
    }
    lines.push(`  ${name}: ${JSON.stringify(text)},`);
  }
  return [
    '// Generated by `scripts/generate-helpers.ts` from `helpers.ts` and `dynamic.ts`. Do not edit.',
    '// The text of each helper of `idlip/helpers`, with types removed.',
    'export const HELPER_SOURCES: Record<string, string> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

const output = await printSource();
if (process.argv.includes('--check')) {
  if (readFileSync(OUTPUT, 'utf8') !== output) {
    throw new Error('helpers-source.ts is out of date. Run `pnpm generate`.');
  }
} else {
  writeFileSync(OUTPUT, output);
}
